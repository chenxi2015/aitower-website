// Generate src/components/workbench/LogoMark.tsx from public/favicon.svg.
// Why: pasting raw SVG into JSX breaks when the source contains XML comments
// (Astro/JSX collapses them into stray text nodes and SSR/CSR markup diverges).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
let svg = fs.readFileSync(path.join(root, 'public/favicon.svg'), 'utf8').trim();

// strip comments, normalize attrs for JSX
svg = svg
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/stop-color=/g, 'stopColor=')
  .replace(/stop-opacity=/g, 'stopOpacity=')
  .replace(/fill-opacity=/g, 'fillOpacity=')
  .replace(/fill-rule=/g, 'fillRule=')
  .replace(/clip-rule=/g, 'clipRule=')
  .replace(/stroke-width=/g, 'strokeWidth=')
  .replace(/stroke-linecap=/g, 'strokeLinecap=')
  .replace(/stroke-linejoin=/g, 'strokeLinejoin=')
  .replace(/xlink:href=/g, 'xlinkHref=')
  .replace(/gradientUnits=/g, 'gradientUnits=');

// make the root svg sizeable via props
svg = svg.replace(
  /<svg([^>]*?)width="1024"\s+height="1024"/,
  '<svg$1width={size} height={size}',
);
svg = svg.replace(/<svg /, '<svg className={className} ');

const out = `// Generated by scripts/gen-logo.cjs from public/favicon.svg — do not hand-edit.
interface Props {
  size?: number;
  className?: string;
}

export default function LogoMark({ size = 24, className = '' }: Props) {
  return (
    ${svg}
  );
}
`;

fs.writeFileSync(path.join(root, 'src/components/workbench/LogoMark.tsx'), out);
console.log('LogoMark.tsx written,', out.length, 'bytes');
